-- ---------------------------------------------------------------------
-- Curated ticker allow-list for workflow 01's stock-universe fetch.
-- Needed because EODHD's combined US exchange feed (NYSE+Nasdaq) returns
-- 18,000+ common-stock tickers when unfiltered -- most illiquid, and
-- backfilling daily OHLCV for all of them (workflow 02) would mean
-- ~18,000 API calls before any liquidity filtering happens downstream
-- (04-11). Restricting workflow 01 to this list keeps the US pipeline to
-- a manageable, genuinely liquid universe from the start.
--
-- Seeded with the current S&P 500 constituents (503 rows; a small number
-- of tickers have dual share classes, e.g. GOOGL/GOOG). Source: the
-- community-maintained "datasets/s-and-p-500-companies" GitHub dataset,
-- fetched 2026-08-20. Empty for a market = no restriction (EGX has no
-- rows here and uses the full provider list, as it always has).
--
-- A market with no rows in this table falls back to the full provider
-- list unfiltered -- this table is an opt-in restriction, not a
-- required config. Expanding US's coverage (e.g. Nasdaq-100, Russell
-- 1000) or making this editable via the Settings UI is future work
-- (Phase 2) once EODHD's Fundamentals/Index-Components API is available
-- on this account's plan (it currently returns 403 Forbidden).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS market_universe_seed (
    market_code  VARCHAR(16) NOT NULL REFERENCES markets(code),
    symbol       VARCHAR(32) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (market_code, symbol)
);

COMMENT ON TABLE market_universe_seed IS 'Curated ticker allow-list restricting workflow 01''s stock-universe fetch for a market. Empty for a market = no restriction (full provider list used, as EGX does today).';

